// Mirrors has_measurement() in supabase/migrations. If one changes, change
// both. Deliberately excludes bare "in", because "1 in 5 tiles" is English.
const MEASUREMENT_RE =
  /(^|[^a-z0-9])[0-9]+([.,][0-9]+)?\s*(mm|cm|m|m2|m²|metre|meter|metres|meters|ft|foot|feet|yard|yards|inch|inches|sq\.?\s*(m|ft|metre|metres|foot|feet)|square\s+(metre|metres|meter|meters|foot|feet))([^a-z0-9]|$)/i;
const MEASUREMENT_QUOTE_RE = /[0-9]\s*(['"])(\s|$|[.,;)])/;

function hasMeasurement(s: unknown): boolean {
  const t = String(s ?? "");
  return MEASUREMENT_RE.test(t) || MEASUREMENT_QUOTE_RE.test(t);
}

// Anything that slipped past the prompt gets replaced rather than deleted, so
// the sentence still reads and the removal is visible to whoever checks it.
function scrub(s: unknown, hits: string[]): string {
  let t = String(s ?? "");
  if (!hasMeasurement(t)) return t;
  hits.push(t.slice(0, 140));
  t = t.replace(new RegExp(MEASUREMENT_RE.source, "gi"), (m) => m.replace(/[0-9.,]+\s*\S*/, "[size removed]"));
  t = t.replace(new RegExp(MEASUREMENT_QUOTE_RE.source, "g"), " [size removed]$2");
  return t;
}

function bearer(req: Request): string {
  return (req.headers.get("authorization") || "").replace(/^Bearer\s+/i, "");
}
function claim(req: Request, key: string): string {
  try {
    return JSON.parse(atob(bearer(req).split(".")[1].replace(/-/g, "+").replace(/_/g, "/")))[key] || "";
  } catch (_) { return ""; }
}
