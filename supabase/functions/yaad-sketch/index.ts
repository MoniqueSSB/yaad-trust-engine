// yaad-sketch
//
// The Site Sketch Pack. A walkthrough video and a set of photos become an
// indicative record of a property: key frames, a room by room condition
// schedule, and a schematic sketch showing rooms, doors and where each photo
// was taken.
//
// THE LINE THIS FUNCTION DOES NOT CROSS.
// It does not measure anything. A phone video carries no scale, so any
// dimension taken from it would be invented, and producing measured drawings
// for reward is regulated work in Jamaica. So: the model is told it has no
// permission to state a dimension, MEASUREMENT_RE scrubs any that appear
// anyway, and has_measurement() in Postgres refuses to let a pack carrying one
// be approved. Three layers, one rule.
//
// The drawing is generated by code, not by the model. The model supplies the
// room list and which rooms connect. Where the boxes land on the page is a
// deterministic layout, which is why it is honest to call it a schematic: it
// shows topology, never geometry.
//
// WHY FRAMES ARRIVE ALREADY EXTRACTED.
// There is no ffmpeg in the edge runtime. Frames are pulled from the video in
// the browser with a <video> element and a canvas, which means the video never
// leaves her machine. Only the frames she chooses are ever uploaded. That is
// the better privacy answer as well as the only workable one.
//
// Actions, in the order the desk calls them:
//   frames    one batch of stills, described by the vision model
//   assemble  all batches, turned into rooms, a sketch and a stored draft
//   render    a pack, turned into the document a client reads

// nvidia/nemotron-nano-12b-v2-vl reached end of life on 26 Aug 2026 and now
// returns HTTP 410. Verified working replacement, checked against a real still
// on the day: it described the shot correctly and refused to call a phone in
// somebody's hand a room, which is the behaviour that matters here.
// Override with the NVIDIA_VISION_MODEL secret; that same secret is read by
// yaad-vision, so setting it fixes both at once.
