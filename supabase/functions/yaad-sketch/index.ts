const esc = (s: unknown) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]!));

// --------------------------------------------------------------- the sketch
//
// Rooms are laid out on a snaking grid in walk order, so two rooms visited one
// after the other end up next to each other on the page. Where a connection
// exists between grid neighbours it is drawn as a real gap in the shared wall
// with a door swing. Where it does not, it is a dashed line, which is the
// honest way to say "these connect, but not like this".
//
// There is not a single number on this drawing other than photo markers, and
// those are labelled as photos so they cannot be mistaken for dimensions.

type Room = {
  key: string; name: string; level?: string; walk_order?: number;
  frames?: number[]; connects?: string[];
  observations?: { note: string; category: string; severity: string; recommend_professional?: boolean }[];
};

function buildSketch(rooms: Room[]): string {
  const W = 168, H = 116, GAP = 40, PAD = 34;
  const n = rooms.length;
  if (!n) return "";
  const cols = Math.max(1, Math.min(4, Math.ceil(Math.sqrt(n))));
  const rowCount = Math.ceil(n / cols);

  const pos = new Map<string, { x: number; y: number; col: number; row: number }>();
  rooms.forEach((r, i) => {
    const row = Math.floor(i / cols);
    // Snake, so the walk reads left to right then right to left.
    const col = row % 2 === 0 ? i % cols : cols - 1 - (i % cols);
    pos.set(r.key, { x: PAD + col * (W + GAP), y: PAD + row * (H + GAP), col, row });
  });

  // The stamp at the foot is the most important text on this drawing, so the
  // canvas is never allowed to be narrower than the stamp needs. A cut-off
  // disclaimer is worse than no disclaimer.
  const width = Math.max(660, PAD * 2 + cols * W + (cols - 1) * GAP);
  const height = PAD * 2 + rowCount * H + (rowCount - 1) * GAP + 84;

  const parts: string[] = [];

  // Connections first, so rooms draw on top of them.
  const drawn = new Set<string>();
  for (const r of rooms) {
    for (const c of r.connects || []) {
      if (c === "outside") continue;
      const pair = [r.key, c].sort().join("|");
      if (drawn.has(pair)) continue;
      const a = pos.get(r.key), b = pos.get(c);
      if (!a || !b) continue;
      drawn.add(pair);

      const sameRow = a.row === b.row && Math.abs(a.col - b.col) === 1;
      const sameCol = a.col === b.col && Math.abs(a.row - b.row) === 1;

      if (sameRow) {
        const x = Math.max(a.x, b.x);          // left edge of the right-hand room
        const y = a.y + H / 2;
        parts.push(`<rect x="${x - GAP - 1}" y="${y - 17}" width="${GAP + 2}" height="34" fill="#fff"/>`);
        parts.push(`<path d="M ${x - GAP} ${y - 17} A 34 34 0 0 1 ${x} ${y + 17}" fill="none" stroke="#B7C9C3" stroke-width="1.4"/>`);
      } else if (sameCol) {
        const y = Math.max(a.y, b.y);
        const x = a.x + W / 2;
        parts.push(`<rect x="${x - 17}" y="${y - GAP - 1}" width="34" height="${GAP + 2}" fill="#fff"/>`);
        parts.push(`<path d="M ${x - 17} ${y - GAP} A 34 34 0 0 0 ${x + 17} ${y}" fill="none" stroke="#B7C9C3" stroke-width="1.4"/>`);
      } else {
        parts.push(`<line x1="${a.x + W / 2}" y1="${a.y + H / 2}" x2="${b.x + W / 2}" y2="${b.y + H / 2}" stroke="#C6D6D1" stroke-width="1.4" stroke-dasharray="5 5"/>`);
      }
    }
  }

  rooms.forEach((r) => {
    const p = pos.get(r.key)!;
    const outside = (r.connects || []).includes("outside");
    parts.push(`<rect x="${p.x}" y="${p.y}" width="${W}" height="${H}" fill="#FBFDFC" stroke="#0F1B17" stroke-width="2" rx="3"/>`);
    if (outside) {
      parts.push(`<rect x="${p.x + W / 2 - 17}" y="${p.y + H - 2}" width="34" height="4" fill="#fff"/>`);
      parts.push(`<text x="${p.x + W / 2}" y="${p.y + H + 17}" text-anchor="middle" font-size="10" fill="#67807A" font-family="'Space Grotesk',sans-serif">outside</text>`);
    }
    const name = esc(r.name).slice(0, 26);
    parts.push(`<text x="${p.x + 12}" y="${p.y + 24}" font-size="13" font-weight="700" fill="#0F1B17" font-family="'Space Grotesk',sans-serif">${name}</text>`);
    if (r.level && r.level !== "ground") {
      parts.push(`<text x="${p.x + 12}" y="${p.y + 40}" font-size="10" fill="#67807A" font-family="'Space Grotesk',sans-serif">${esc(r.level)}</text>`);
    }
    (r.frames || []).slice(0, 8).forEach((f, i) => {
      const cx = p.x + 22 + (i % 4) * 30, cy = p.y + H - 34 + Math.floor(i / 4) * 26;
      parts.push(`<circle cx="${cx}" cy="${cy}" r="11" fill="#14B8A6"/>`);
      parts.push(`<text x="${cx}" y="${cy + 4}" text-anchor="middle" font-size="10" font-weight="700" fill="#04120F" font-family="'Space Grotesk',sans-serif">${f}</text>`);
    });
  });

  const legendY = PAD + rowCount * H + (rowCount - 1) * GAP + 42;
  parts.push(`<circle cx="${PAD + 11}" cy="${legendY - 4}" r="11" fill="#14B8A6"/>`);
  parts.push(`<text x="${PAD + 11}" y="${legendY}" text-anchor="middle" font-size="10" font-weight="700" fill="#04120F" font-family="'Space Grotesk',sans-serif">n</text>`);
  parts.push(`<text x="${PAD + 30}" y="${legendY}" font-size="11" fill="#4A5F5A" font-family="'Space Grotesk',sans-serif">where photo n was taken</text>`);
  // Two short lines rather than one long one, so it fits at any room count.
  parts.push(`<text x="${PAD}" y="${legendY + 22}" font-size="11" fill="#8A5A00" font-family="'Space Grotesk',sans-serif">Schematic only. Rooms are drawn the same size whatever their real size.</text>`);
  parts.push(`<text x="${PAD}" y="${legendY + 37}" font-size="11" fill="#8A5A00" font-family="'Space Grotesk',sans-serif">Nothing here is to scale and nothing has been measured.</text>`);

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="100%" role="img" aria-label="Schematic sketch of the rooms walked, not to scale">
<rect width="${width}" height="${height}" fill="#fff"/>
${parts.join("\n")}
</svg>`;
}

